"""Generate the synthetic Day 1 payment-attempt dataset.

The generator is stochastic but reproducible for a fixed seed. Historical
customer fields represent decision-time snapshots. Recovery is generated by
a noisy latent mechanism rather than a direct copy of the policy rules.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

DATASET_ROWS = 5000
DATASET_COLUMNS = 19
TIME_COLUMN = "event_timestamp"
FEATURE_COLUMNS = [
    "attempt_id", "payment_id", "customer_id", "amount_inr", "payment_method",
    "attempt_number", "customer_tenure_days", "successful_payment_count",
    "failed_payment_count", "historical_recovery_count", "customer_opted_out",
    "failure_code", "failure_category", "issuer_response", "device_type",
    "country", "fraud_risk",
]
LABEL_COLUMNS = ["recovered"]
OUTCOME_COLUMNS = ["recovery_time_hours"]

FAILURE_MAP = {
    "T001": ("temporary_decline", "issuer_temporary_decline"),
    "T002": ("temporary_decline", "network_timeout"),
    "H001": ("hard_decline", "issuer_hard_decline"),
    "M001": ("payment_method_issue", "invalid_or_expired_method"),
    "A001": ("authentication_required", "authentication_required"),
    "U001": ("unknown", "unknown_issuer_error"),
}


def dataset_contract() -> dict[str, object]:
    return {
        "rows": DATASET_ROWS,
        "columns": DATASET_COLUMNS,
        "metadata": [TIME_COLUMN],
        "features": FEATURE_COLUMNS.copy(),
        "labels": LABEL_COLUMNS.copy(),
        "outcomes": OUTCOME_COLUMNS.copy(),
        "point_in_time": True,
        "synthetic": True,
    }


def _sigmoid(value: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-value))


def generate_dataset(n_rows: int = DATASET_ROWS, seed: int = 42) -> pd.DataFrame:
    """Return decision-time features, event time, and the recovery label."""
    if n_rows <= 0:
        raise ValueError("n_rows must be positive")

    rng = np.random.default_rng(seed)
    customer_ids = np.array([f"CUS-{idx:04d}" for idx in rng.integers(1, 1001, n_rows)])
    payment_ids = np.array([f"PAY-{idx:06d}" for idx in range(1, n_rows + 1)])
    attempt_ids = np.array([f"ATT-{idx:06d}" for idx in range(1, n_rows + 1)])
    event_timestamp = pd.date_range("2026-01-01T00:00:00Z", periods=n_rows, freq="15min")

    # All customer-history fields are sampled before the current attempt.
    tenure = rng.integers(30, 1501, n_rows)
    successful = rng.poisson(np.clip(tenure / 180, 0.5, 12), n_rows)
    failed = rng.poisson(1.8, n_rows)
    historical_recovery = np.minimum(
        rng.binomial(successful + 1, 0.18), failed + 3
    )

    amount = np.round(np.exp(rng.normal(np.log(2200), 0.9, n_rows)), 2)
    amount = np.clip(amount, 99, 100000)
    methods = rng.choice(["card", "upi", "netbanking", "wallet"], n_rows, p=[0.42, 0.38, 0.12, 0.08])
    attempt_number = rng.choice([1, 2, 3, 4], n_rows, p=[0.66, 0.22, 0.09, 0.03])
    opted_out = rng.random(n_rows) < 0.025
    fraud_risk = rng.random(n_rows) < 0.018
    devices = rng.choice(["android", "ios", "web"], n_rows, p=[0.48, 0.22, 0.30])
    countries = rng.choice(["IN", "AE", "SG", "US"], n_rows, p=[0.88, 0.04, 0.04, 0.04])

    failure_codes = rng.choice(
        list(FAILURE_MAP), n_rows,
        p=[0.25, 0.16, 0.18, 0.17, 0.14, 0.10],
    )
    categories = np.array([FAILURE_MAP[code][0] for code in failure_codes])
    issuers = np.array([FAILURE_MAP[code][1] for code in failure_codes])

    category_effect = {
        "temporary_decline": 0.95,
        "payment_method_issue": 0.25,
        "authentication_required": 0.05,
        "unknown": -0.15,
        "hard_decline": -1.45,
    }
    effect = np.array([category_effect[c] for c in categories])
    logit = (
        -0.35
        + effect
        + 0.11 * np.log1p(successful)
        + 0.16 * np.minimum(historical_recovery, 5)
        - 0.28 * np.maximum(attempt_number - 1, 0)
        - 0.22 * fraud_risk.astype(float)
        - 0.10 * np.log1p(amount / 1000)
        + 0.12 * (methods == "upi")
        + 0.10 * (devices == "android")
        + rng.normal(0, 0.75, n_rows)
    )
    recovered = rng.random(n_rows) < _sigmoid(logit)

    return pd.DataFrame(
        {
            "attempt_id": attempt_ids,
            "payment_id": payment_ids,
            "customer_id": customer_ids,
            "event_timestamp": event_timestamp,
            "amount_inr": amount,
            "payment_method": methods,
            "attempt_number": attempt_number,
            "customer_tenure_days": tenure,
            "successful_payment_count": successful,
            "failed_payment_count": failed,
            "historical_recovery_count": historical_recovery,
            "customer_opted_out": opted_out,
            "failure_code": failure_codes,
            "failure_category": categories,
            "issuer_response": issuers,
            "device_type": devices,
            "country": countries,
            "fraud_risk": fraud_risk,
            "recovered": recovered,
        },
        columns=["attempt_id", "payment_id", "customer_id", TIME_COLUMN] + FEATURE_COLUMNS[3:] + LABEL_COLUMNS,
    )


def generate_csv(path: str = "data/payment_attempts.csv", rows: int = DATASET_ROWS, seed: int = 42) -> None:
    generate_dataset(rows, seed).to_csv(path, index=False)


if __name__ == "__main__":
    generate_csv()
    print(f"Generated {DATASET_ROWS} rows with {DATASET_COLUMNS} columns")
